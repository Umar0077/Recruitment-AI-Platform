/** Real PostgreSQL, fictional fixtures, one rollback transaction. No reset or seed. */
import "reflect-metadata";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { parse } from "dotenv";
import { PrismaClient } from "@prisma/client";
import { ConfigService } from "@nestjs/config";
import type { Response } from "express";
import { AdminAuthService, ADMIN_COOKIE, passwordHash, sessionHash, type AdminRequest } from "../../src/modules/auth/admin-auth.service";
import { initializeAdmin } from "../../src/modules/auth/admin-bootstrap";
import { AuditService } from "../../src/modules/audit/audit.module";
import type { PrismaService } from "../../src/database/prisma.service";
import type { EnvironmentVariables } from "../../src/config/env.validation";
let phase = "configuration";
async function main() {
  const env = parse(readFileSync(resolve(__dirname, "../../.env")));
  const target = env.TEST_DATABASE_URL!;
  const url = new URL(target);
  assert(["localhost", "127.0.0.1", "[::1]"].includes(url.hostname) && /_test$/.test(url.pathname) && target !== env.DATABASE_URL);
  const db = new PrismaClient({ datasources: { db: { url: target } }, log: [] });
  const rollback = new Error("ROLLBACK"), passed: string[] = [];
  const email = `fictional-admin-${randomUUID()}@example.test`;
  const password = `Fictional-${randomUUID()}aA7!`, next = `Changed-${randomUUID()}aA8!`;
  try {
    try {
      await db.$transaction(async tx => {
        const adapter = new Proxy(tx, { get: (object, prop) => prop === "$transaction" ? async (fn: (client: typeof tx) => unknown) => fn(tx) : Reflect.get(object, prop) }) as unknown as PrismaService;
        for (const code of ["SUPER_ADMIN", "RECRUITER", "REVIEWER"] as const) await tx.role.upsert({ where: { code }, create: { code, name: code }, update: {} });
        phase = "bootstrap";
        assert.equal(await tx.adminCredential.count(), 0, "Requires test database with no administrator fixtures");
        const hash = await passwordHash(password);
        assert(hash.startsWith("$argon2id$v=19$m=65536,t=3,p=1$"));
        assert.equal(await initializeAdmin(adapter, hash, email), true);
        assert.equal(await initializeAdmin(adapter, hash, email), false);
        assert.equal(await tx.adminCredential.count(), 1);
        passed.push("Argon2id bootstrap, one-time marker and idempotency");
        const config = new ConfigService<EnvironmentVariables, true>({ FRONTEND_ORIGINS: "http://localhost:3000", NODE_ENV: "development" });
        const service = new AdminAuthService(adapter, new AuditService(adapter), config);
        const req = { headers: { origin: "http://localhost:3000", "x-admin-request": "1" }, method: "POST", secure: false } as unknown as AdminRequest;
        let token = "", cookieOptions: Record<string, unknown> = {};
        const res = { cookie: (_: string, value: string, options: Record<string, unknown>) => { token = value; cookieOptions = options; }, setHeader: () => undefined } as unknown as Response;
        phase = "credential failure and lockout";
        for (let i = 0; i < 5; i++) await assert.rejects(service.login(email, "incorrect", req, res), { code: "UNAUTHENTICATED" });
        let credential = await tx.adminCredential.findUniqueOrThrow({ where: { email } });
        assert.equal(credential.failedLoginAttempts, 5); assert(credential.lockedUntil! > new Date());
        await assert.rejects(service.login(email, password, req, res), { code: "UNAUTHENTICATED" });
        await tx.adminCredential.update({ where: { id: credential.id }, data: { lockedUntil: new Date(0) } });
        await service.login(email.toUpperCase(), password, req, res);
        assert.equal(cookieOptions.httpOnly, true); assert.equal(cookieOptions.sameSite, "strict");
        assert.equal(token.length, 43);
        assert.equal((await tx.adminSession.findFirstOrThrow()).tokenHash, sessionHash(token));
        passed.push("incorrect passwords, temporary lockout, expiry unlock, opaque hashed session and cookie flags");
        req.headers.cookie = `${ADMIN_COOKIE}=${token}`; req.method = "GET";
        req.user = (await service.authenticate(req))!;
        assert(req.user.roles.includes("SUPER_ADMIN")); assert.equal(req.mustChangePassword, true);
        phase = "password change";
        await assert.rejects(service.changePassword(req, res, "wrong", next), { code: "UNAUTHENTICATED" });
        await assert.rejects(service.changePassword(req, res, password, password), { code: "VALIDATION_FAILED" });
        await service.changePassword(req, res, password, next);
        assert.equal(await service.authenticate(req), null);
        credential = await tx.adminCredential.findUniqueOrThrow({ where: { email } });
        assert.equal(credential.mustChangePassword, false); assert.notEqual(credential.passwordHash, hash);
        await service.login(email, next, req, res); req.headers.cookie = `${ADMIN_COOKIE}=${token}`; req.user = (await service.authenticate(req))!;
        passed.push("current-password verification, reuse rejection, mandatory-change flag and all-session revocation");
        phase = "account management";
        const created = await service.create(req, `fictional-hr-${randomUUID()}@example.test`, "Fictional HR", password, "RECRUITER");
        const accounts = await service.list(req); assert.equal(accounts.length, 2); assert(!JSON.stringify(accounts).includes("passwordHash"));
        await assert.rejects(service.manage(req, credential.id, { active: false }), { code: "CONFLICT" });
        await assert.rejects(service.create(req, "fictional@example.test", "Fictional", password, "SUPER_ADMIN"), { code: "FORBIDDEN" });
        await service.manage(req, created.id, { role: "REVIEWER", active: false });
        await assert.rejects(service.login(created.email, password, req, res), { code: "UNAUTHENTICATED" });
        const lesser = { ...req, user: { ...req.user, roles: ["REVIEWER"] } } as AdminRequest;
        assert.throws(() => service.list(lesser), { code: "FORBIDDEN" });
        passed.push("HR roles, disabled accounts, self/Super Admin protection and safe list responses");
        phase = "session expiry and logout";
        await tx.adminSession.update({ where: { id: req.adminSessionId }, data: { lastSeenAt: new Date(Date.now() - 31 * 60000) } });
        assert.equal(await service.authenticate(req), null);
        await tx.adminSession.update({ where: { id: req.adminSessionId }, data: { lastSeenAt: new Date(), expiresAt: new Date(0) } });
        assert.equal(await service.authenticate(req), null);
        await service.login(email, next, req, res); req.headers.cookie = `${ADMIN_COOKIE}=${token}`; await service.authenticate(req);
        await service.logout(req, res); assert.equal(await service.authenticate(req), null); assert.equal(token, "");
        await service.login(email, next, req, res); req.headers.cookie = `${ADMIN_COOKIE}=${token}`; await service.authenticate(req);
        await service.logout(req, res, true); assert.equal(await service.authenticate(req), null);
        passed.push("idle and absolute expiry, logout and revoke-all");
        phase = "operator recovery";
        await initializeAdmin(adapter, hash, email, true);
        credential = await tx.adminCredential.findUniqueOrThrow({ where: { email } });
        assert(credential.mustChangePassword); assert.equal(credential.failedLoginAttempts, 0);
        assert.equal(await tx.adminSession.count({ where: { credentialId: credential.id, revokedAt: null } }), 0);
        const history = await service.history(req);
        assert(history.some(a => a.action === "admin.operator_recovery"));
        assert(history.some(a => a.action === "admin.password_changed"));
        passed.push("operator recovery requires new password, revokes sessions and audits actions");
        throw rollback;
      }, { timeout: 120000 });
    } catch (error) { if (error !== rollback) throw error; }
    phase = "rollback verification";
    assert.equal(await db.adminCredential.count({ where: { email } }), 0);
    process.stdout.write(JSON.stringify({ status: "passed", checks: passed, fixturesRolledBack: true, existingRecordsModified: false }, null, 2) + "\n");
  } finally { await db.$disconnect(); }
}
void main().catch(() => { process.stderr.write(JSON.stringify({ status: "failed", phase, sensitiveDetailsSuppressed: true }) + "\n"); process.exitCode = 1; });
